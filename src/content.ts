export function findQuestion(id: string): Question | undefined {
  const existing = questions.find((q) => q.id === id);
  if (existing) return existing;
  const match = /^generated:(\d+\.\d+\.\d+\.\d+):(\d+):(network|broadcast)$/.exec(id);
  if (!match) return undefined;
  const octets = match[1].split('.').map(Number),
    prefix = Number(match[2]);
  if (octets.some((n) => n > 255) || prefix < 20 || prefix > 30) return undefined;
  const address = octets.reduce((a, b) => a * 256 + b, 0),
    size = 2 ** (32 - prefix);
  const net = Math.floor(address / size) * size,
    value = match[3] === 'network' ? net : net + size - 1;
  const formatted = [24, 16, 8, 0].map((s) => Math.floor(value / 2 ** s) % 256).join('.');
  return {
    ...q(
      'subnetting',
      0,
      `Was ist ${match[3] === 'network' ? 'die Netzadresse' : 'der Broadcast'} von ${match[1]}/${prefix}?`,
      undefined,
      formatted,
      `Bei /${prefix} bleiben ${32 - prefix} Hostbits: ${size} Adressen pro Block. ${match[3] === 'network' ? 'Alle Hostbits auf 0 setzen.' : 'Alle Hostbits auf 1 setzen.'} Das ergibt ${formatted}.`,
      `Bestimme zuerst die Blockgrösse: 2 hoch (32 − ${prefix}).`,
    ),
    id,
  };
}
export function generatedQuestion(): Question {
  const prefix = [20, 24, 25, 26, 27, 28, 29, 30][Math.floor(Math.random() * 8)];
  const ip = `10.${Math.floor(Math.random() * 256)}.${Math.floor(Math.random() * 256)}.${Math.floor(Math.random() * 256)}`;
  return findQuestion(
    `generated:${ip}:${prefix}:${Math.random() > 0.5 ? 'network' : 'broadcast'}`,
  )!;
}
